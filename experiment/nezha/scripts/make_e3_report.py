#!/usr/bin/env python3
"""Generate E3 tables (S1 vs S2, plus modality ablations) from machine
artifacts. Nothing hand-typed."""
import json
import sys

E2_RES = sys.argv[1] if len(sys.argv) > 1 else "/home/user/e2-runs/results"
MODES = [("rank_service_dedup", "AC@1 service (primary)"),
         ("rank_service_raw", "AC@1 service raw"),
         ("rank_inner", "AC@1 inner")]


def row(agg):
    return (f"{agg['AC@1_pct']:.2f}/{agg['AC@3_pct']:.2f}"
            + (f"/{agg['AC@5_pct']:.2f}" if "AC@5_pct" in agg else "")
            + f" | {agg['MRR']:.3f} | {agg['unlocalized']}")


def main():
    print("<!-- generated by make_e3_report.py; do not hand-edit numbers -->")
    for ns in ("hipster", "ts"):
        try:
            s1 = json.load(open(f"{E2_RES}/s1-{ns}.cases.json"))["summary"]
            s2 = json.load(open(f"{E2_RES}/s2-{ns}.cases.json"))["summary"]
        except FileNotFoundError:
            continue
        print(f"\n## {ns} — S1 vs S2 (n={s1['n_cases']})\n")
        print("| metric | S1 @1/@3/@5 | MRR | unloc | S2 @1/@3/@5 | MRR | unloc |")
        print("|---|---|---|---|---|---|---|")
        for mode, label in MODES:
            print(f"| {label} | {row(s1['aggregates'][mode])} | "
                  f"{row(s2['aggregates'][mode])} |")
        print(f"\nCandidate sets: S1 {s1['candidate_sizes']}; "
              f"S2 {s2['candidate_sizes']}")

    try:
        abl = json.load(open(f"{E2_RES}/s1-ablations-ts.json"))
    except FileNotFoundError:
        return
    print("\n## ts — S1 modality ablations (n=45)\n")
    print("| variant | svc_dedup AC@1/AC@3 | MRR | unloc | "
          "inner AC@1/AC@3 | MRR | unloc |")
    print("|---|---|---|---|---|---|---|")
    base = json.load(open(f"{E2_RES}/s1-ts.cases.json"))["summary"]["aggregates"]
    print(f"| (full S1) | {base['rank_service_dedup']['AC@1_pct']:.2f}/"
          f"{base['rank_service_dedup']['AC@3_pct']:.2f} | "
          f"{base['rank_service_dedup']['MRR']:.3f} | "
          f"{base['rank_service_dedup']['unlocalized']} | "
          f"{base['rank_inner']['AC@1_pct']:.2f}/"
          f"{base['rank_inner']['AC@3_pct']:.2f} | "
          f"{base['rank_inner']['MRR']:.3f} | "
          f"{base['rank_inner']['unlocalized']} |")
    for variant, data in abl.items():
        a = data["aggregates"]
        print(f"| {variant} | {a['rank_service_dedup']['AC@1_pct']:.2f}/"
              f"{a['rank_service_dedup']['AC@3_pct']:.2f} | "
              f"{a['rank_service_dedup']['MRR']:.3f} | "
              f"{a['rank_service_dedup']['unlocalized']} | "
              f"{a['rank_inner']['AC@1_pct']:.2f}/"
              f"{a['rank_inner']['AC@3_pct']:.2f} | "
              f"{a['rank_inner']['MRR']:.3f} | "
              f"{a['rank_inner']['unlocalized']} |")


if __name__ == "__main__":
    main()
