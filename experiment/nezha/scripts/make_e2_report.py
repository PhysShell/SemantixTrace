#!/usr/bin/env python3
"""Generate the E2 N1-vs-S1 comparison tables from machine artifacts.

Inputs:
  - N1: experiment/nezha/results/e0/eval/<ns>-service.eval.json
        (corrected semantics recomputed over the artifact's own runs)
  - S1: <e2 runroot>/results/s1-<ns>.cases.json

Every number is read from the artifacts; nothing is hand-typed.
"""
import json
import sys

RESOURCE_TYPES = {"cpu_contention", "cpu_consumed", "network_delay"}

E0_EVAL = sys.argv[1] if len(sys.argv) > 1 else \
    "/home/user/SemantixTrace/experiment/nezha/results/e0/eval"
E2_RES = sys.argv[2] if len(sys.argv) > 2 else "/home/user/e2-runs/results"

# preregistered-semantics pairing: N1 mode name -> S1 mode name
MODES = [("service_dedup", "rank_service_dedup", "AC@1 service (primary)"),
         ("service_raw", "rank_service_raw", "AC@1 service raw"),
         ("dense", "rank_inner", "AC@1 inner (dense)")]


def agg_s1(cases, mode):
    n = len(cases)
    ranks = [c["evaluation"][mode] for c in cases]
    hit = [r for r in ranks if r is not None]
    return {
        "AC@1_pct": 100.0 * sum(1 for r in hit if r <= 1) / n,
        "AC@3_pct": 100.0 * sum(1 for r in hit if r <= 3) / n,
        "AC@5_pct": 100.0 * sum(1 for r in hit if r <= 5) / n,
        "MRR": sum(1.0 / r for r in hit) / n,
        "unlocalized": n - len(hit),
    }


def main():
    print("<!-- generated by make_e2_report.py; do not hand-edit numbers -->")
    for ns in ("hipster", "ts"):
        try:
            n1 = json.load(open(f"{E0_EVAL}/{ns}-service.eval.json"))
            s1 = json.load(open(f"{E2_RES}/s1-{ns}.cases.json"))
        except FileNotFoundError as e:
            print(f"\n## {ns}: MISSING ARTIFACT ({e})")
            continue
        n1_cases = {(c["inject_time"], c["inject_pod"], c["inject_type"]): c
                    for c in n1["cases"] if "missing_in_log" not in c}
        s1_cases = s1["cases"]
        n = len(s1_cases)
        print(f"\n## {ns} (n={n})\n")
        print("| metric | N1 @1/@3/@5 | N1 MRR | N1 unloc | "
              "S1 @1/@3/@5 | S1 MRR | S1 unloc |")
        print("|---|---|---|---|---|---|---|")
        for n1_mode, s1_mode, label in MODES:
            a1 = n1["summary"]["aggregates"][n1_mode]
            a2 = agg_s1(s1_cases, s1_mode)
            print(f"| {label} | "
                  f"{a1['AC@1_pct']:.2f}/{a1['AC@3_pct']:.2f}/{a1['AC@5_pct']:.2f} | "
                  f"{a1['MRR']:.3f} | {a1['unlocalized']} | "
                  f"{a2['AC@1_pct']:.2f}/{a2['AC@3_pct']:.2f}/{a2['AC@5_pct']:.2f} | "
                  f"{a2['MRR']:.3f} | {a2['unlocalized']} |")

        n1_sizes = n1["summary"]["candidate_set_sizes"]
        s1_sizes = sorted(c["evaluation"]["n_candidates"] for c in s1_cases)
        print(f"\nCandidate sets: N1 min/med/max = {n1_sizes[0]}/"
              f"{n1_sizes[len(n1_sizes)//2]}/{n1_sizes[-1]}; "
              f"S1 = {s1_sizes[0]}/{s1_sizes[len(s1_sizes)//2]}/{s1_sizes[-1]}")

        # per-case service_dedup deltas
        print("\n### Per-case rank changes (service_dedup, N1 -> S1)\n")
        print("| case | type | N1 | S1 |")
        print("|---|---|---|---|")
        moved = 0
        for c in s1_cases:
            key = (c["inject_time"], c["inject_pod"], c["inject_type"])
            n1c = n1_cases.get(key)
            r1 = n1c.get("rank_service_dedup") if n1c else "?"
            r2 = c["evaluation"]["rank_service_dedup"]
            if r1 != r2:
                moved += 1
                print(f"| {c['case_id']} | {c['inject_type']} | {r1} | {r2} |")
        if not moved:
            print("| (none) | | | |")

        print("\n### S1 fault-type breakdown (hits@1 / cases, service_dedup)\n")
        for label, pred in (("resource", lambda t: t in RESOURCE_TYPES),
                            ("code-defect", lambda t: t not in RESOURCE_TYPES)):
            sub = [c for c in s1_cases if pred(c["inject_type"])]
            hits = sum(1 for c in sub
                       if (c["evaluation"]["rank_service_dedup"] or 99) <= 1)
            print(f"- {label}: {hits}/{len(sub)}")

        # ingestion totals; §8 failure records carry no ingestion block
        # (Codex round-13 P2, D-027)
        evaluated = [c for c in s1_cases if "ingestion" in c]
        tot_rej = sum(sum(c["ingestion"]["rejections"].values())
                      for c in evaluated)
        tot_new = sum(c["ingestion"]["drain3_new_clusters"] for c in evaluated)
        print(f"\nIngestion: total rejected records across cases = {tot_rej}; "
              f"drain3 new clusters = {tot_new}")
        failed = [c["case_id"] for c in s1_cases if "failure" in c]
        if failed:  # §8: report failures separately, clean runs unchanged
            print(f"\nFailed cases (counted unlocalized, §8): "
                  f"{len(failed)} — {', '.join(failed)}")


if __name__ == "__main__":
    main()
