#!/usr/bin/env python3
"""Generate the E0 reproduction comparison tables from machine artifacts.

Inputs (per configuration):
  - our run:      <runroot>/<config>/artifact.log, run-meta.txt
  - author log:   <nezha>/log/<committed name>
  - evaluator:    <runroot>/eval/<config>.eval.json  (independent_eval.py output)

Output: markdown to stdout. Nothing here is hand-typed; every number is read
from the artifacts.
"""
import json
import re
import sys

RUNROOT = sys.argv[1] if len(sys.argv) > 1 else "/home/user/e0-runs"
NEZHA = sys.argv[2] if len(sys.argv) > 2 else "/home/user/Nezha"

CONFIGS = [
    ("hipster-service", "OnlineBoutique_service_result.log", "AS"),
    ("hipster-inner", "OnlineBoutique_innerservice_result.log", "AIS"),
    ("ts-service", "Trainticket_service_result.log", "AS"),
    ("ts-inner", "Trainticket_innerservice_Result.log", "AIS"),
]

VEC_RE = re.compile(r"pattern_ranker.py:\d+: (\[[\d, ]*\])\s*$")
PCT_RE = re.compile(r"pattern_ranker.py:\d+: ([\d.]+) %")
SCORE_RE = re.compile(
    r"(\d{4}-\d{2}-\d{2} \d{2}:\d{2}(?::\d{2})?) Inject Ground Truth: (\S+), (\S+) score (\d+)\s*$")


def extract(path):
    """final rank vector, % lines, and per-case (time, pod, type, rank)."""
    vec, pcts, scores = None, [], []
    try:
        with open(path, errors="replace") as f:
            for line in f:
                m = VEC_RE.search(line)
                if m:
                    vec = m.group(1)  # keep last occurrence
                m = PCT_RE.search(line)
                if m:
                    pcts.append(m.group(1))
                m = SCORE_RE.search(line)
                if m:
                    scores.append(m.groups())
    except FileNotFoundError:
        return None, None, None
    return vec, pcts[-3:], scores


def main():
    print("<!-- generated by make_e0_report.py; do not hand-edit numbers -->")
    print()
    print("| config | wall(s) | exit | ours %@1/@3/@5 | authors %@1/@3/@5 | "
          "% match | rank-vector match | per-case score-line match |")
    print("|---|---|---|---|---|---|---|---|")
    for config, author_name, label in CONFIGS:
        ours_vec, ours_pct, ours_scores = extract(f"{RUNROOT}/{config}/artifact.log")
        auth_vec, auth_pct, auth_scores = extract(f"{NEZHA}/log/{author_name}")
        try:
            meta = open(f"{RUNROOT}/{config}/run-meta.txt").readline().strip()
            wall = re.search(r"wall_seconds=(\d+)", meta).group(1)
            rc = re.search(r"exit_code=(\d+)", meta).group(1)
        except (FileNotFoundError, AttributeError):
            wall, rc = "?", "?"
        if ours_pct is None:
            print(f"| {config} | {wall} | {rc} | RUN MISSING | | | | |")
            continue
        pct_match = "YES" if ours_pct == auth_pct else "NO"
        vec_match = "YES" if ours_vec == auth_vec else "NO"
        # per-case: authors' logs may differ in whitespace; compare tuples
        sc_match = "YES" if ours_scores == auth_scores else (
            f"NO ({sum(1 for a, b in zip(ours_scores, auth_scores) if a != b)}"
            f"+{abs(len(ours_scores) - len(auth_scores))} diffs)")
        print(f"| {config} | {wall} | {rc} | {'/'.join(ours_pct)} | "
              f"{'/'.join(auth_pct)} | {pct_match} | {vec_match} | {sc_match} |")

    print()
    print("### Independent evaluator (first-principles) summaries")
    print()
    print("| config | n | in-log | align-err | parser-vs-artifact rank "
          "mismatches | historical AC@1/@3/@5 | MRR | unlocalized | "
          "dense AC@1 | service_raw AC@1 | service_dedup AC@1 |")
    print("|---|---|---|---|---|---|---|---|---|---|---|")
    for config, _, _ in CONFIGS:
        try:
            d = json.load(open(f"{RUNROOT}/eval/{config}.eval.json"))
        except FileNotFoundError:
            print(f"| {config} | EVAL MISSING | | | | | | | | | |")
            continue
        s = d["summary"]
        a = s["aggregates"]
        h = a["historical"]
        print(f"| {config} | {s['n_faults_ground_truth']} | {s['n_cases_in_log']} | "
              f"{len(s['alignment_errors'])} | "
              f"{s['claim_check_artifact_vs_historical']['mismatch_count']} | "
              f"{h['AC@1_pct']:.2f}/{h['AC@3_pct']:.2f}/{h['AC@5_pct']:.2f} | "
              f"{h['MRR']:.3f} | {h['unlocalized']} | "
              f"{a['dense']['AC@1_pct']:.2f} | {a['service_raw']['AC@1_pct']:.2f} | "
              f"{a['service_dedup']['AC@1_pct']:.2f} |")

    print()
    print("### Candidate-set sizes (per config: min/median/max)")
    print()
    for config, _, _ in CONFIGS:
        try:
            d = json.load(open(f"{RUNROOT}/eval/{config}.eval.json"))
        except FileNotFoundError:
            continue
        sizes = d["summary"]["candidate_set_sizes"]
        if sizes:
            med = sizes[len(sizes) // 2]
            print(f"- {config}: min {sizes[0]}, median {med}, max {sizes[-1]}")


if __name__ == "__main__":
    main()
