#!/usr/bin/env python3
"""Generate E1 measurement-audit tables from independent_eval.py outputs.

For each configuration this emits, from machine artifacts only:
  1. aggregate metrics under each rank semantics (historical / dense /
     service_raw / service_dedup), with @1/@3/@5, MRR, unlocalized;
  2. the per-case list of every fault whose rank differs between semantics
     (the "every changed case" requirement of E1);
  3. a fault-type breakdown (resource vs code-defect) per semantics.

Usage: make_e1_report.py <eval_json> [<eval_json> ...]
"""
import json
import sys

RESOURCE_TYPES = {"cpu_contention", "cpu_consumed", "network_delay"}
MODES = ("historical", "dense", "service_raw", "service_dedup")


def fmt_rank(r):
    return "-" if r is None else str(r)


def hit(r, k):
    return r is not None and r <= k


def main():
    print("<!-- generated by make_e1_report.py; do not hand-edit numbers -->")
    for path in sys.argv[1:]:
        d = json.load(open(path))
        s = d["summary"]
        cases = [c for c in d["cases"] if "missing_in_log" not in c]
        n = s["n_faults_ground_truth"]
        name = path.rsplit("/", 1)[-1].replace(".eval.json", "")
        print(f"\n## {name} (n={n})\n")

        print("| semantics | AC@1 | AC@3 | AC@5 | MRR | unlocalized |")
        print("|---|---|---|---|---|---|")
        for mode in MODES:
            a = s["aggregates"][mode]
            print(f"| {mode} | {a['AC@1_pct']:.2f}% | {a['AC@3_pct']:.2f}% | "
                  f"{a['AC@5_pct']:.2f}% | {a['MRR']:.3f} | {a['unlocalized']} |")

        print("\n### Cases whose rank differs across semantics\n")
        print("| case | inject | type | artifact | historical | dense | "
              "service_raw | service_dedup |")
        print("|---|---|---|---|---|---|---|---|")
        rows = 0
        for c in cases:
            ranks = [c.get("rank_historical"), c.get("rank_dense"),
                     c.get("rank_service_raw"), c.get("rank_service_dedup")]
            if len(set(ranks)) > 1 or c.get("artifact_claimed_rank") != ranks[0]:
                rows += 1
                print(f"| {c['case_id']} | {c['inject_time']} | "
                      f"{c['inject_type']} | "
                      f"{fmt_rank(c.get('artifact_claimed_rank'))} | "
                      f"{fmt_rank(ranks[0])} | {fmt_rank(ranks[1])} | "
                      f"{fmt_rank(ranks[2])} | {fmt_rank(ranks[3])} |")
        if not rows:
            print("| (none) | | | | | | | |")

        print("\n### Fault-type breakdown (AC@1 hits / cases)\n")
        print("| class | cases | " + " | ".join(MODES) + " |")
        print("|---|---|" + "---|" * len(MODES))
        for label, pred in (
                ("resource", lambda t: t in RESOURCE_TYPES),
                ("code-defect", lambda t: t not in RESOURCE_TYPES)):
            sub = [c for c in cases if pred(c["inject_type"])]
            cells = []
            for mode in MODES:
                k = f"rank_{mode}"
                cells.append(f"{sum(1 for c in sub if hit(c.get(k), 1))}/{len(sub)}")
            print(f"| {label} | {len(sub)} | " + " | ".join(cells) + " |")


if __name__ == "__main__":
    main()
